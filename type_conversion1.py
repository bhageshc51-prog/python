# Type Conversion in Python

# String to Integer
number = "100"
converted_number = int(number)

print("String value:", number)
print("Converted to Integer:", converted_number)
print(type(converted_number))


# Integer to Float
marks = 85
marks_float = float(marks)

print("\nInteger value:", marks)
print("Converted to Float:", marks_float)
print(type(marks_float))


# Float to String
percentage = 92.5
percentage_string = str(percentage)

print("\nFloat value:", percentage)
print("Converted to String:", percentage_string)
print(type(percentage_string))
