# Type Conversion in Python

num1 = "100"
num2 = "50"

# Converting string to integer
sum = int(num1) + int(num2)

print("Addition :", sum)

# Integer to float
marks = 85
percentage = float(marks)

print("Percentage :", percentage)

# Float to integer
value = 45.89
new_value = int(value)

print("Converted Value :", new_value)

# Integer to string
number = 500
text = str(number)

print(type(text))
